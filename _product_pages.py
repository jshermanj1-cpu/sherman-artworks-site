def head_block(p, lang):
    url = page_url(p, lang)
    t = TEXT[lang]
    nm = name(p, lang)
    title = f"{nm} | {t['brand']}"
    if lang == "he":
        desc = p["description_he"]
    else:
        desc = f"{p['description_en']} {p['measurements']}."
        if len(desc) > 160:
            desc = p["description_en"]
    share = image(p["photos"][0], "w_1200,h_630,c_pad,b_rgb:faf7f2,q_auto,f_auto")
    rows = [
        f"<title>{html.escape(title)}</title>",
        f'<meta name="description" content="{e(desc)}" />',
        f'<meta property="og:title" content="{e(nm)}" />',
        f'<meta property="og:description" content="{e(desc)}" />',
        '<meta property="og:type" content="product" />',
        f'<meta property="og:url" content="{url}" />',
        f'<meta property="og:image" content="{share}" />',
        '<meta name="twitter:card" content="summary_large_image" />',
        f'<meta name="twitter:title" content="{e(title)}" />',
        f'<meta name="twitter:description" content="{e(desc)}" />',
        f'<meta name="twitter:image" content="{share}" />',
        f'<link rel="canonical" href="{url}" />',
        f'<link rel="alternate" hreflang="en" href="{page_url(p, "en")}" />',
        f'<link rel="alternate" hreflang="he-IL" href="{page_url(p, "he")}" />',
        f'<link rel="alternate" hreflang="x-default" href="{page_url(p, "en")}" />',
    ]
    return "\n  ".join(rows)


def strip_one(src, pattern, label, flags=re.S, count_ok=(1,)):
    found = len(re.findall(pattern, src, flags))
    if found not in count_ok:
        raise RuntimeError(f"{label}: expected {count_ok} match(es), found {found}")
    return re.sub(pattern, "", src, flags=flags)


def rootify(src, base):
    """Relative href/src in the template, made root-absolute for /products/."""
    def fix(m):
        value = m.group(2)
        if not value or value.startswith(SKIP):
            return m.group(0)
        return m.group(1) + urljoin(base, value) + '"'
    return re.sub(r'(\b(?:href|src)=")([^"]*)"', fix, src)


def build(p, products, lang, landing_src, shape_src, d, s):
    out = landing_src
    graph = None
    for raw in re.findall(r'<script type="application/ld\+json">(.*?)</script>', out, re.S):
        node = json.loads(raw)
        if "@graph" in node and any(n.get("@type") == "MerchantReturnPolicy" for n in node["@graph"]):
            graph = '<script type="application/ld+json">' + raw + "</script>"
    if not graph:
        raise RuntimeError(f"{lang} landing page: no shared seller/shipping/returns block")
    wa_svg = re.search(r'id="modalOrderCta".*?(<svg.*?</svg>)', out, re.S).group(1)

    # Head: drop the landing page's identity, then write this product's.
    out = re.sub(r'\s*<script type="application/ld\+json">.*?</script>', "", out, flags=re.S)
    out = re.sub(r"\s*<!-- /?hanukkah:jsonld -->", "", out)
    out = strip_one(out, r"\s*<title>.*?</title>", f"{lang} title")
    out = re.sub(r'\s*<meta\b(?=[^>]*\b(?:name|property)="(?:description|og:[\w:]+|twitter:[\w:]+)")[^>]*>', "", out)
    out = strip_one(out, r'<link\b(?=[^>]*\brel="canonical")[^>]*>', f"{lang} canonical")
    out = re.sub(r'\s*<link\b(?=[^>]*\brel="alternate")(?=[^>]*\bhreflang=)[^>]*>', "", out)
    viewport = re.search(r'<meta\b[^>]*name="viewport"[^>]*>', out)
    if not viewport:
        raise RuntimeError(f"{lang}: no viewport meta")
    out = out[:viewport.end()] + "\n  " + head_block(p, lang) + out[viewport.end():]
    if lang == "en":
        # The URL decides the language, as on the /he/ pages: a stale Hebrew
        # choice in localStorage would otherwise translate only half this page.
        out = out.replace("<head>", "<head>\n  <script>window.__SA_LANG='en';</script>", 1)
    out = out.replace("</head>", jsonld_blocks(p, lang, landing_src, shape_src, graph) + "\n</head>", 1)
    out = re.sub(r"(<style>.*?)(\s*</style>)", lambda m: m.group(1) + CSS.rstrip() + m.group(2), out, count=1, flags=re.S)

    # Language toggles go to this product's twin, not the landing page's.
    out = out.replace("location.href='/he/hanukkah-menorahs.html'", f"location.href='{page_path(p, 'he')}'")
    out = out.replace("location.href='/hanukkah-menorahs.html'", f"location.href='{page_path(p, 'en')}'")

    # Body: the product instead of the grid; no product window, questions or grid script.
    main = main_html(p, products, lang, d, s).replace("{WA_SVG}", wa_svg)
    if len(re.findall(r'<main id="main-content">', out)) != 1:
        raise RuntimeError(f"{lang}: expected one <main>")
    out = re.sub(r'<main id="main-content">.*?</main>', lambda m: main, out, count=1, flags=re.S)
    at = out.find('id="productModal"')
    trust = re.search(r'<section\b[^>]*class="trust-strip"', out[at:]) if at >= 0 else None
    if not trust:
        raise RuntimeError(f"{lang}: product window or trust strip not found")
    start = out.rfind("<div", 0, at)
    comment = out.rfind("<!-- PRODUCT MODAL -->", 0, start)
    if comment >= 0 and not out[comment + len("<!-- PRODUCT MODAL -->"):start].strip():
        start = comment
    out = out[:start] + out[at + trust.start():]
    guide = re.search(r'<section\b[^>]*id="guide"[^>]*>.*?</section>\s*', out, re.S)
    if not guide or "<section" in guide.group(0)[8:]:
        raise RuntimeError(f"{lang}: questions section not found or nested")
    out = out[:guide.start()] + out[guide.end():]
    out = strip_one(out, r'\s*<script src="/?js/hanukkah-menorahs\.js[^"]*"></script>', f"{lang} grid script")

    data = {"id": p["id"], "sku": p["sku"], "name": name(p, lang), "name_en": p["name_en"],
            "name_he": p.get("name_he", ""), "color_en": p["color_en"], "price_ils": p["price_ils"],
            "photos": p["photos"], "page": page_path(p, lang).lstrip("/"),
            "photo_alt": TEXT[lang]["photo"].format(name=name(p, lang), n="{n}", total=len(p["photos"]))}
    script = SCRIPT % {"data": json.dumps(data, ensure_ascii=False), "cdn": CDN}
    out = out.replace("</body>", script + "\n</body>", 1)
    return rootify(out, "/he/" if lang == "he" else "/")


def sitemap_block(urls, xml, changed, today):
    old = dict(re.findall(r"<loc>(.*?)</loc>\s*<lastmod>(.*?)</lastmod>", xml, re.S))
    rows = []
    for url in urls:
        lastmod = today if url in changed or url not in old else old[url]
        rows.append("  <url>\n    <loc>%s</loc>\n    <lastmod>%s</lastmod>\n"
                    "    <changefreq>weekly</changefreq>\n    <priority>0.7</priority>\n  </url>" % (url, lastmod))
    return "\n".join(rows)


def update_sitemap(xml, block):
    pat = re.compile(re.escape(SITEMAP_START) + r"\n.*?" + re.escape(SITEMAP_END), re.S)
    new = SITEMAP_START + "\n" + block + "\n" + SITEMAP_END
    if pat.search(xml):
        return pat.sub(lambda m: new, xml, count=1)
    anchor = "  <!-- Hebrew (/he/) pages -->"
    if anchor in xml:
        return xml.replace(anchor, new + "\n\n" + anchor, 1)
    return xml.replace("</urlset>", new + "\n\n</urlset>", 1)


def main():
    check = "--check" in sys.argv
    products = live(load())
    if not products:
        raise SystemExit(f"no live {CATEGORY} products")
    sources = {}
    for lang in ("en", "he"):
        prefix = "he/" if lang == "he" else ""
        landing = (SITE / prefix / LANDING).read_text(encoding="utf-8")
        shapes = {k: (SITE / prefix / cfg["file"]).read_text(encoding="utf-8") for k, cfg in SHAPES.items()}
        sources[lang] = (landing, shapes, *strings(lang, landing))

    wanted, stale, changed_urls = {}, [], set()
    for p in products:
        for lang in ("en", "he"):
            landing, shapes, d, s = sources[lang]
            rel = page_path(p, lang).lstrip("/")
            wanted[rel] = build(p, products, lang, landing, shapes[p["shape"]], d, s)
    for rel, out in wanted.items():
        path = SITE / rel
        if not path.exists() or path.read_text(encoding="utf-8") != out:
            stale.append(rel)
            changed_urls.add(f"{BASE}/{rel}")
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                with open(path, "w", encoding="utf-8", newline="\n") as fh:
                    fh.write(out)
    for folder in (SITE / "products", SITE / "he" / "products"):
        for old in sorted(folder.glob("*.html")) if folder.exists() else []:
            rel = old.relative_to(SITE).as_posix()
            if rel not in wanted:
                stale.append(rel + " (no longer a live menorah)")
                if not check:
                    old.unlink()

    urls = [page_url(p, "en") for p in products] + [page_url(p, "he") for p in products]
    xml = SITEMAP.read_text(encoding="utf-8")
    new_xml = update_sitemap(xml, sitemap_block(urls, xml, changed_urls, datetime.date.today().isoformat()))
    if new_xml != xml:
        stale.append("sitemap.xml")
        if not check:
            with open(SITEMAP, "w", encoding="utf-8", newline="\n") as fh:
                fh.write(new_xml)

    note = f"{len(products)} menorahs, {len(wanted)} pages"
    if not stale:
        print(f"Product pages are current ({note})")
        return 0
    shown = stale if len(stale) <= 6 else stale[:6] + [f"... {len(stale) - 6} more"]
    print(("stale: " if check else "wrote: ") + ", ".join(shown) + f" ({note})")
    return 1 if check else 0


if __name__ == "__main__":
    sys.exit(main())
