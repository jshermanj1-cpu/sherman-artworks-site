def e(s):
    return html.escape(s, quote=True)


def page_path(p, lang):
    return ("/he" if lang == "he" else "") + f"/products/{p['id']}.html"


def page_url(p, lang):
    return BASE + page_path(p, lang)


def landing_path(lang, rel=LANDING):
    return ("/he/" if lang == "he" else "/") + rel


def sibling(products, p, **want):
    keys = {"finish": p["finish"], "shape": p["shape"], "color_en": p["color_en"]}
    keys.update(want)
    return next((x for x in products if all(x.get(k) == v for k, v in keys.items())), None)


def strings(lang, landing_src):
    """The landing page's T_PAGE plus js/site.js's T_SITE, for one language."""
    page = parse_he_dict(landing_src, "const T_PAGE", lang)
    site = T_SITE_HE if lang == "he" else T_SITE_EN
    need = ["bc_shop", "choose_shape", "choose_metal", "choose_glass", "shape_half_moon",
            "shape_rectangular", "shape_trapezoid", "metal_silver", "metal_gold", "your_choice",
            "choice_shape", "choice_glass", "choice_metal", "spec_measurements", "measurements_value",
            "spec_price", "modal_order", "modal_shipping", "modal_shipping_link",
            "price_regular", "price_hanukkah"]
    missing = [k for k in need if k not in page] + [k for k in ("cat9_title", "add_cart", "color_note") if k not in site]
    if missing:
        raise RuntimeError(f"{lang}: missing translation keys {', '.join(missing)}")
    return page, site


